const DICTS: Record<Language, Dict> = { fa, en };

export type PracticeText = (
  key: string,
  values?: Record<string, string | number>,
) => string;

/** Localized strings for the practice features. Numbers in `values` are formatted for the language. */
export function usePT(): PracticeText {
  const { language } = useLanguage();

  return useCallback(
    (key, values) => {
      const template = DICTS[language][key] ?? en[key] ?? key;

      if (!values) {
        return template;
      }

      return Object.entries(values).reduce(
        (text, [name, value]) =>
          text
            .split(`{${name}}`)
            .join(
              typeof value === "number"
                ? formatNumber(value, language)
                : String(value),
            ),
        template,
      );
    },
    [language],
  );
}
