function surahOf(pages: readonly MushafPageData[]): MushafSurah {
  return {
    surahId: pages[0]!.surahId,
    pages,
    verses: pages.flatMap((page) => page.verses),
  };
}

// ---------------------------------------------------------------------------------------------
// Madinah Mushaf 1441H (QCF v4, calligraphy by Uthman Taha) for every other surah.
// The page data is generated by scripts/build-mushaf-data.py into data/qcf4/mushafQcf4.json.
// ---------------------------------------------------------------------------------------------

interface RawQcf4Page {
  /** Mushaf page number. */
  p: number;
  /** Font family of the page. */
  f: string;
  /** Font units per em. */
  u: number;
  /** Widest line of the whole printed page, in font units. */
  w: number;
  /** One glyph code per word / verse marker. */
  c: number[];
  /** Glyph advances in font units. */
  a: number[];
  /** [from, to, 1 = centered] */
  l: [number, number, number][];
  /** [ayah, from, to, markerIndex] */
  v: [number, number, number, number][];
  /** 1 when the surah starts on this page. */
  h: number;
  /** 1 when the bismillah is printed above the surah on this page. */
  b: number;
}

const QCF4_PAGES = qcf4Pages as unknown as Record<string, RawQcf4Page[]>;
const QCF4_TITLES = qcf4Titles as unknown as Record<string, string>;
/** Line pitch / line width of the tuned QCF v1 layout (1.41 em at 14.4 em per line). */
const LINE_PITCH_PER_WIDTH = 1.41 / 14.4;

function buildQcf4Page(surahId: number, raw: RawQcf4Page): MushafPageData {
  const title = QCF4_TITLES[String(surahId)] ?? "";
  const info = SURAHS.find((surah) => surah.id === surahId);
  const hasBismillah = raw.b === 1 && surahId !== 1 && surahId !== 9;

  return {
    surahId,
    pageNumber: raw.p,
    fontFamily: raw.f,
    unitsPerEm: raw.u,
    cells: raw.c.map((code) => [code]),
    advances: raw.a,
    lines: raw.l.map(([from, to, centered]) => ({
      from,
      to,
      alignment: centered === 1 ? "center" : "justify",
    })),
    verses: raw.v.map(([ayah, from, to, markerIndex]) => ({
      ayah,
      from,
      to,
      markerIndex,
    })),
    frame: {
      runningHeader: juzTitle(juzOfPage(raw.p)),
      runningTitle: title,
    },
    surahHeader:
      raw.h === 1
        ? {
            title,
            order: surahId,
            versesCount: info?.verses ?? 0,
            ...(hasBismillah
              ? {
                  bismillahFont: BISMILLAH_FONT_FAMILY,
                  bismillahCodepoints: BISMILLAH_CODEPOINTS,
                  bismillahAdvances: BISMILLAH_ADVANCES,
                }
              : {}),
          }
        : undefined,
    referenceWidth: raw.w,
    lineHeightRatio: LINE_PITCH_PER_WIDTH * (raw.w / raw.u),
  };
}

const surahCache = new Map<number, MushafSurah>();

export const MUSHAF_SURAH_IDS: readonly number[] = JUZ30_SURAHS.map(
  (surah) => surah.id,
);

/** Every Juz 30 surah has its own page data (An-Naba keeps its hand-tuned QCF v1 pages). */
export function getMushafSurah(surahId: number): MushafSurah | undefined {
  const cached = surahCache.get(surahId);

  if (cached) {
    return cached;
  }

  let surah: MushafSurah | undefined;

  if (surahId === PAGE582_SURAH_ID) {
    surah = surahOf([NABA_P582, NABA_P583]);
  } else {
    const rawPages = QCF4_PAGES[String(surahId)];

    surah = rawPages
      ? surahOf(rawPages.map((raw) => buildQcf4Page(surahId, raw)))
      : undefined;
  }

  if (surah) {
    surahCache.set(surahId, surah);
  }

  return surah;
}

/** The surah a new user starts with (An-Naba). */
export const DEFAULT_SURAH_ID = PAGE582_SURAH_ID;

export function hasMushafPage(surahId: number): boolean {
  return getMushafSurah(surahId) !== undefined;
}

export function pageForAyah(surah: MushafSurah, ayah: number): MushafPageData {
  return (
    surah.pages.find((page) =>
      page.verses.some((verse) => verse.ayah === ayah),
    ) ?? surah.pages[0]!
  );
}

export function cellText(page: MushafPageData, index: number): string {
  return String.fromCodePoint(...(page.cells[index] ?? [0x20]));
}
